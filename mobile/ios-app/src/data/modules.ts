export type ModuleId = string;

export function getModule(moduleId: ModuleId) {
  return modules.find((module) => module.id === moduleId) || modules[0];
}

export function resolveDetailWebPath(module: ModuleConfig, entity: Entity) {
  if (typeof module.detailWebPath === "function") return module.detailWebPath(entity);
  if (module.detailWebPath && entity.id) return module.detailWebPath.replace("{id}", String(entity.id));
  return module.webPath;
}
