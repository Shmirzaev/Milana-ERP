export type ModuleConfig = {
  id: string;
  section: ModuleSection;
  title: string;
  description: string;
  icon: IconName;
  endpoint?: string;
  detailEndpoint?: string;
  webPath?: string;
  createWebPath?: string;
  detailWebPath?: string | ((entity: Entity) => string | undefined);
  searchParam?: string;
  statusOptions?: string[];
  permissionHints?: string[];
  actions?: ModuleAction[];
  getTitle?: (entity: Entity) => string;
  getSubtitle?: (entity: Entity) => string;
  getMeta?: (entity: Entity) => string;
};

function text(value: unknown) {
  return formatValue(value);
}

function pathForWorkOrder(row: Entity) {
  const id = firstPresent(row, ["id", "work_order_id"]);
  const operation = String(firstPresent(row, ["operation"]) || "").trim();
  if (!id) return undefined;
  return operation ? `/work-orders/${id}/${operation}` : `/work-orders`;
}

function pathForDepartment(code: string) {
  return `/departments/${code}`;
}

